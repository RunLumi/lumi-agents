let current: Lang = detect();

export function detect(): Lang {
  try {
    const saved = localStorage.getItem("lumi-lang");
    if (saved === "en" || saved === "vi") return saved;
  } catch {}
  const langs = navigator.languages || [navigator.language || "en"];
  for (const lang of langs) {
    if (lang.toLowerCase().startsWith("vi")) return "vi";
  }
  return "en";
}

export function t(key: string): string {
  const dict = STRINGS[current] || STRINGS.en;
  return dict[key] != null ? dict[key] : STRINGS.en[key] != null ? STRINGS.en[key] : key;
}

export function currentLang(): Lang {
  return current;
}

export function setLang(lang: Lang): void {
  if (lang !== "en" && lang !== "vi") return;
  current = lang;
  try { localStorage.setItem("lumi-lang", lang); } catch {}
  document.documentElement.lang = lang;
}
